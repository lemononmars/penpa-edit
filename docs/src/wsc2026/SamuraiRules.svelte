<div class="samurai-rules">
 <p class="base-rule">Use digits 1–9 once in every row, column and 3×3 box of each grid.</p>
 <dl>
  <div><dt>Top left · No Three in a Line</dt><dd>No three consecutive cells on a marked line may all be odd or all be even.</dd></div>
  <div><dt>Top right · Creasing</dt><dd>Digits on each line strictly increase or strictly decrease.</dd></div>
  <div><dt>Centre · Palindrome</dt><dd>Each line reads the same in both directions.</dd></div>
  <div><dt>Bottom left & right · Clone Along Line</dt><dd>The marked lines contain the same digits in the same order, allowing either direction.</dd></div>
 </dl>
 <p class="scoring">Completed grids score 90, 80, 70, 60 and 50 points in solve order. Each must agree with the overall solution.</p>
